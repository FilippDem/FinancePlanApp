def get_strategy_base_name(name: str) -> str:
    if name.endswith(' (statistical)'):
        return name[:-14]
    if name.endswith(' (custom)'):
        return name[:-9]
    return name


def normalize_strategy_name(name: str) -> str:
    if not name:
        return "Average (statistical)"
    if name.endswith(' (statistical)') or name.endswith(' (custom)'):
        return name
    if name in STATISTICAL_STRATEGIES_LEGACY:
        return STATISTICAL_STRATEGIES[STATISTICAL_STRATEGIES_LEGACY.index(name)]
    if name == "Moderate":
        return "Average (statistical)"
    return f"{name} (custom)"


def _lookup(table: dict, location: str, strategy: str):
    if location in table:
        loc = table[location]
        if strategy in loc:
            return copy.deepcopy(loc[strategy])
        base = get_strategy_base_name(strategy)
        if base in loc:
            return copy.deepcopy(loc[base])
        if f"{base} (statistical)" in loc:
            return copy.deepcopy(loc[f"{base} (statistical)"])
    return None


def adult_template(location: str, strategy: str) -> dict:
    """City -> US state -> Canadian province -> Seattle Average (v0.8 priority)."""
    r = ref()
    strategy = normalize_strategy_name(strategy)
    for table in (r["ADULT_EXPENSE_TEMPLATES"], r["STATE_EXPENSE_TEMPLATES"], r["PROVINCE_EXPENSE_TEMPLATES"]):
        t = _lookup(table, location, strategy)
        if t is not None:
            return t
    state = CITY_TO_STATE.get(location)
    if state:
        t = _lookup(r["STATE_EXPENSE_TEMPLATES"], state, strategy)
        if t is not None:
            return t
    return copy.deepcopy(r["ADULT_EXPENSE_TEMPLATES"]["Seattle"]["Average (statistical)"])


def family_template(location: str, strategy: str, custom: dict | None = None) -> dict | None:
    strategy = normalize_strategy_name(strategy)
    t = _lookup(ref()["FAMILY_EXPENSE_TEMPLATES"], location, strategy)
    if t is None and custom:
        t = _lookup(custom, location, strategy)
    return t


def _age_scale(age: int) -> float:
    if age < 2: return 0.25
    if age < 5: return 0.30
    if age < 12: return 0.40
    if age < 16: return 0.50
    if age < 19: return 0.70
    if age < 23: return 0.50
    if age < 26: return 0.30
    return 0.0


