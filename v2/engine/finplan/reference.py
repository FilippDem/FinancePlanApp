@lru_cache(maxsize=256)
def _children_template_cached(location: str, strategy: str) -> str:
    t = _lookup(ref()["CHILDREN_EXPENSE_TEMPLATES"], location, strategy)
    if t is None:
        level = 'Conservative' if 'Conservative' in strategy else 'High-end' if 'High' in strategy else 'Average'
        t = generate_children_template_from_adult(adult_template(location, strategy), level)
    return json.dumps(t)


def children_template(location: str, strategy: str) -> dict:
    """{category: [31 annual amounts for ages 0..30]} in template-base-year dollars."""
    return json.loads(_children_template_cached(location, normalize_strategy_name(strategy)))


# ---- College & private school lookups (from v0.8 get_child_expenses) ----
PRIVATE_SCHOOL = {'Seattle': 20000, 'Sacramento': 18000, 'Houston': 15000, 'New York': 35000,
                  'San Francisco': 32000, 'Los Angeles': 25000, 'Portland': 17000}
PUBLIC_TUITION = {'Seattle': 12000, 'Sacramento': 10000, 'Houston': 11000, 'New York': 13000,
                  'San Francisco': 10000, 'Los Angeles': 10000, 'Portland': 12000}
PRIVATE_TUITION = {'Seattle': 55000, 'Sacramento': 50000, 'Houston': 48000, 'New York': 60000,
                   'San Francisco': 58000, 'Los Angeles': 56000, 'Portland': 52000}
ROOM_BOARD = {'Seattle': 18000, 'Sacramento': 15000, 'Houston': 12000, 'New York': 25000,
              'San Francisco': 24000, 'Los Angeles': 20000, 'Portland': 16000}


def child_expenses_for_age(child: dict, age: int, legacy_table: list | None = None) -> dict:
    """Port of v0.8 get_child_expenses (amounts in today's dollars, not inflated)."""
    if age < 0 or age > 30:
        return {}
    at_college = 18 <= age <= 21
    location = child.get('college_location', 'Seattle') if at_college else child.get('template_state', 'Seattle')
    strategy = child.get('template_strategy', 'Average')
    custom = child.get('custom_expenses')  # v2 addition: per-child override table
    if isinstance(custom, dict) and custom:
        exp = {k: (v[age] if isinstance(v, list) and age < len(v) else 0) for k, v in custom.items()}
    else:
        tmpl = children_template(location or 'Seattle', strategy or 'Average')
        if tmpl and age < len(tmpl.get('Groceries', tmpl.get('Food', []))):
            exp = {k: (v[age] if age < len(v) else 0) for k, v in tmpl.items()}
        elif legacy_table and age < len(legacy_table):
            exp = {k: v for k, v in legacy_table[age].items() if k != 'Age'}
        else:
            exp = {}
    if child.get('school_type', 'Public') == 'Private' and 5 <= age <= 17:
        exp['Education'] = exp.get('Education', 0) + PRIVATE_SCHOOL.get(child.get('template_state', 'Seattle'), 20000)
    if at_college:
        exp['Food'] = exp.get('Food', 0) * 0.3
        exp['Transportation'] = exp.get('Transportation', 0) * 0.4
        exp['Entertainment'] = exp.get('Entertainment', 0) * 0.5
        if child.get('college_type', 'Public') == 'Public':
            tuition = PUBLIC_TUITION.get(location, 12000)
        else:
            tuition = PRIVATE_TUITION.get(location, 55000)
        # v0.8 added tuition on top of the template's own college 'Education'
        # amount (double counting). v2 replaces it: tuition + room & board.
        exp['Education'] = tuition + ROOM_BOARD.get(location, 18000)
    return exp


def location_tax_info(location: str | None):
    """Returns (type, info) like v0.8 get_location_type."""
    r = ref()
    if not location:
        return 'unknown', None
    if location in r["US_STATE_TAX_INFO"]:
        return 'us_state', r["US_STATE_TAX_INFO"][location]
    if location in r["COUNTRY_TAX_INFO"]:
        return 'country', r["COUNTRY_TAX_INFO"][location]
    if location in CITY_TO_STATE:
        st = CITY_TO_STATE[location]
        if st in r["US_STATE_TAX_INFO"]:
            return 'us_state', r["US_STATE_TAX_INFO"][st]
    # Province templates -> treat as Canada if present
    if location in r["PROVINCE_EXPENSE_TEMPLATES"] and "Canada" in r["COUNTRY_TAX_INFO"]:
        return 'country', r["COUNTRY_TAX_INFO"]["Canada"]
    return 'unknown', None


def all_locations() -> list[str]:
    r = ref()
    locs = set(r["ADULT_EXPENSE_TEMPLATES"]) | set(r["STATE_EXPENSE_TEMPLATES"]) | set(r["PROVINCE_EXPENSE_TEMPLATES"])
    return sorted(locs)
